/**
 * Return type for useNotifications hook
 */
export interface UseNotificationsReturn {
  /** List of notifications */
  notifications: UserNotification[];
  /** Number of unread notifications */
  unreadCount: number;
  /** Whether notifications are loading */
  isLoading: boolean;
  /** Error if any */
  error: Error | null;
  /** Mark a notification as read */
  markAsRead: (notificationId: string) => Promise<void>;
  /** Mark all notifications as read */
  markAllAsRead: () => Promise<void>;
  /** Delete a notification */
  deleteNotification: (notificationId: string) => Promise<void>;
  /** Clear all notifications */
  clearAll: () => Promise<void>;
  /** Refresh notifications */
  refresh: () => Promise<void>;
}

/**
 * Return type for useBroadcasts hook
 */
export interface UseBroadcastsReturn {
  /** List of active broadcasts */
  broadcasts: BroadcastNotification[];
  /** Whether broadcasts are loading */
  isLoading: boolean;
  /** Error if any */
  error: Error | null;
  /** Dismiss a broadcast */
  dismissBroadcast: (broadcastId: string) => void;
  /** Track broadcast impression */
  trackImpression: (broadcastId: string) => void;
  /** Track broadcast click */
  trackClick: (broadcastId: string) => void;
  /** Check if broadcast was dismissed */
  isDismissed: (broadcastId: string) => boolean;
  /** Refresh broadcasts from cache */
  refresh: () => Promise<void>;
}

/**
 * Return type for useNotificationEvents hook
 */
export interface UseNotificationEventsReturn {
  /** Trigger a notification event */
  trigger: (payload: NotificationEventPayload) => Promise<void>;
  /** Trigger account created event */
  triggerAccountCreated: (data: { userName: string; email: string }) => Promise<void>;
  /** Trigger new device signin event */
  triggerNewDeviceSignin: (data: { deviceName: string; location?: string }) => Promise<void>;
  /** Trigger password changed event */
  triggerPasswordChanged: () => Promise<void>;
  /** Trigger profile updated event */
  triggerProfileUpdated: (data: { changes: string[] }) => Promise<void>;
  /** Trigger CRUD event */
  triggerCrudEvent: (data: {
    action: 'created' | 'updated' | 'deleted';
    entityType: string;
    entityName: string;
  }) => Promise<void>;
  /** Trigger app tip event */
  triggerAppTip: (data: { tipId: string; title: string; body: string }) => Promise<void>;
}

