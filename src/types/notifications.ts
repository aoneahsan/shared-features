/**
 * Notification template for standard events
 * Collection: zaions_notification_templates/{templateId}
 */
export interface NotificationTemplate {
  /** Template ID */
  id: string;
  /** Template name for admin reference */
  name: string;
  /** Event type this template is for */
  eventType: StandardEventType | string;
  /** Notification category */
  category: NotificationCategory;
  /** Title with placeholders: "Welcome to {{appName}}, {{userName}}!" */
  title: string;
  /** Message with placeholders */
  message: string;
  /** List of variable names used in title/message */
  variables: string[];
  /** Visual notification type */
  type: NotificationType;
  /** Whether notifications from this template are important */
  isImportant: boolean;
  /** Default action URL (can use placeholders) */
  actionUrl?: string;
  /** Default action button text */
  actionText?: string;
  /** Whether this template is enabled */
  enabled: boolean;
  /** When template was created */
  createdAt: Date | Timestamp;
  /** When template was last updated */
  updatedAt: Date | Timestamp;
}

/**
 * Input for creating a template
 */
export interface CreateTemplateInput {
  name: string;
  eventType: StandardEventType | string;
  category: NotificationCategory;
  title: string;
  message: string;
  variables: string[];
  type: NotificationType;
  isImportant: boolean;
  actionUrl?: string;
  actionText?: string;
  enabled: boolean;
}

