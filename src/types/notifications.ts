/**
 * Event definition for triggering notifications
 */
export interface NotificationEventDefinition {
  /** Event type identifier */
  type: StandardEventType | string;
  /** Event display name */
  name: string;
  /** Event description */
  description: string;
  /** Default notification category */
  category: NotificationCategory;
  /** Default notification type */
  notificationType: NotificationType;
  /** Default priority */
  priority: NotificationPriority;
  /** Available template variables */
  variables: string[];
  /** Whether this event is enabled by default */
  defaultEnabled: boolean;
}

/**
 * Event trigger payload
 */
export interface NotificationEventPayload {
  /** Event type */
  type: StandardEventType | string;
  /** User ID to notify */
  userId: string;
  /** Variable values for template interpolation */
  data: Record<string, string | number | boolean>;
  /** Optional override for notification title */
  titleOverride?: string;
  /** Optional override for notification message */
  messageOverride?: string;
  /** Optional action URL */
  actionUrl?: string;
  /** Optional action text */
  actionText?: string;
  /** Additional metadata */
  metadata?: Record<string, unknown>;
}

