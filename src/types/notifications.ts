/**
 * In-App Notification System Type Definitions
 *
 * Type definitions for the unified notification system including
 * broadcasts, user notifications, templates, and preferences.
 *
 * Architecture:
 * - Broadcasts: Stored in shared-features Firebase (zaions_broadcasts)
 * - User notifications: Stored in consumer project's Firebase
 * - Templates: Stored in shared-features Firebase (zaions_notification_templates)
 *
 * @author Ahsan Mahmood <aoneahsan@gmail.com>
 */

import { Timestamp } from 'firebase/firestore';

// ============================================================================
// NOTIFICATION CATEGORIES & TYPES
// ============================================================================

/**
 * Standard notification categories for grouping and filtering
 */
export type NotificationCategory =
  | 'system' // Maintenance, updates, outages
  | 'account' // Welcome, security, profile changes
  | 'activity' // CRUD operations, user actions
  | 'report' // Weekly/monthly summaries
  | 'promotional' // Tips, features, holidays
  | 'social'; // Shares, mentions, comments

/**
 * Visual notification type for styling
 */
export type NotificationType =
  | 'info' // General information
  | 'success' // Positive feedback
  | 'warning' // Attention needed
  | 'error' // Something went wrong
  | 'reminder' // Time-based reminder
  | 'milestone' // Achievement/progress
  | 'announcement'; // Important announcement

/**
 * Priority levels for notifications
 */
export type NotificationPriority = 'urgent' | 'high' | 'normal' | 'low';

/**
 * Source of the notification
 */
export type NotificationSource =
  | 'system' // Auto-generated by system
  | 'event' // Triggered by user action
  | 'broadcast' // Cross-project announcement
  | 'admin'; // Sent by admin

/**
 * Broadcast display variants
 */
export type BroadcastVariant = 'banner' | 'modal' | 'toast' | 'bell';

/**
 * Broadcast status
 */
export type BroadcastStatus = 'draft' | 'scheduled' | 'active' | 'ended';

/**
 * Target platforms for notifications
 */
export type NotificationPlatform = 'web' | 'android' | 'ios';

/**
 * Target audience for broadcasts
 */
export type NotificationAudience = 'all' | 'authenticated' | 'anonymous';

// ============================================================================
// STANDARD EVENT TYPES
// ============================================================================

/**
 * Standard event types that trigger notifications
 */
export type StandardEventType =
  // Account Events
  | 'ACCOUNT_CREATED'
  | 'ACCOUNT_WELCOME'
  | 'NEW_DEVICE_SIGNIN'
  | 'PASSWORD_CHANGED'
  | 'PROFILE_UPDATED'
  | 'ACCOUNT_DELETED'
  // Report Events
  | 'DAILY_SUMMARY'
  | 'WEEKLY_SUMMARY'
  | 'MONTHLY_SUMMARY'
  | 'QUARTERLY_SUMMARY'
  | 'YEARLY_SUMMARY'
  // Promotional Events
  | 'APP_TIP'
  | 'HIDDEN_FEATURE'
  | 'NEW_FEATURE_ANNOUNCEMENT'
  | 'HOLIDAY_GREETING'
  // System Events
  | 'SYSTEM_MAINTENANCE'
  | 'APP_UPDATE_AVAILABLE'
  | 'DATA_EXPORT_READY'
  // Activity Events (Generic CRUD)
  | 'ITEM_CREATED'
  | 'ITEM_UPDATED'
  | 'ITEM_DELETED'
  | 'BULK_OPERATION_COMPLETE';

// ============================================================================
// BASE NOTIFICATION INTERFACE
// ============================================================================

/**
 * Base notification fields shared across all notification types
 */
export interface BaseNotification {
  /** Unique notification ID */
  id: string;
  /** Notification title */
  title: string;
  /** Notification message/body */
  message: string;
  /** Visual type for styling */
  type: NotificationType;
  /** Category for grouping/filtering */
  category: NotificationCategory;
  /** Whether the notification has been read */
  isRead: boolean;
  /** Whether this notification is important/pinned */
  isImportant?: boolean;
  /** Optional action URL to navigate to */
  actionUrl?: string;
  /** Optional action button text */
  actionText?: string;
  /** When the notification was created */
  createdAt: Date | Timestamp;
  /** When the notification was read */
  readAt?: Date | Timestamp;
  /** Additional metadata for custom use */
  metadata?: Record<string, unknown>;
}

// ============================================================================
// USER NOTIFICATION
// ============================================================================

/**
 * User-specific notification stored in consumer project's Firebase
 * Collection: {prefix}_notifications/{notificationId}
 */
export interface UserNotification extends BaseNotification {
  /** User ID this notification belongs to */
  userId: string;
  /** How the notification was generated */
  source: NotificationSource;
  /** Reference to source entity (broadcast ID, event ID, etc.) */
  sourceId?: string;
  /** Event type if triggered by event */
  eventType?: StandardEventType | string;
  /** When the notification expires (auto-delete) */
  expiresAt?: Date | Timestamp;
}

/**
 * Input for creating a user notification
 */
export interface CreateUserNotificationInput {
  userId: string;
  title: string;
  message: string;
  type: NotificationType;
  category: NotificationCategory;
  source: NotificationSource;
  sourceId?: string;
  eventType?: StandardEventType | string;
  isImportant?: boolean;
  actionUrl?: string;
  actionText?: string;
  expiresAt?: Date;
  metadata?: Record<string, unknown>;
}

// ============================================================================
// BROADCAST NOTIFICATION
// ============================================================================

/**
 * Cross-project broadcast notification stored in shared-features Firebase
 * Collection: zaions_broadcasts/{broadcastId}
 */
export interface BroadcastNotification extends BaseNotification {
  /** Target project IDs (empty = all projects) */
  targetProjects: string[];
  /** Target platforms */
  targetPlatforms: NotificationPlatform[];
  /** Target audience */
  targetAudience: NotificationAudience;
  /** Broadcast status */
  status: BroadcastStatus;
  /** When the broadcast becomes active */
  startDate: Date | Timestamp;
  /** When the broadcast ends (null = no end) */
  endDate?: Date | Timestamp | null;
  /** Display priority (1-100, higher = more important) */
  priority: number;
  /** Whether user can dismiss this broadcast */
  dismissible: boolean;
  /** How to display this broadcast */
  variant: BroadcastVariant;
  /** Total impressions count */
  impressions: number;
  /** Total clicks count */
  clicks: number;
  /** Admin user ID who created */
  createdBy: string;
  /** Admin user ID who last updated */
  updatedBy?: string;
}

/**
 * Input for creating a broadcast
 */
export interface CreateBroadcastInput {
  title: string;
  message: string;
  type: NotificationType;
  category: NotificationCategory;
  targetProjects: string[];
  targetPlatforms: NotificationPlatform[];
  targetAudience: NotificationAudience;
  startDate: Date;
  endDate?: Date | null;
  priority: number;
  dismissible: boolean;
  variant: BroadcastVariant;
  isImportant?: boolean;
  actionUrl?: string;
  actionText?: string;
  metadata?: Record<string, unknown>;
}

/**
 * Input for updating a broadcast
 */
export interface UpdateBroadcastInput extends Partial<CreateBroadcastInput> {
  id: string;
  status?: BroadcastStatus;
}

